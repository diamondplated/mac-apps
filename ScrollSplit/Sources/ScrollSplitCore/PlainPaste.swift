import AppKit

/// One type's data in one pasteboard item, in the order the item listed it.
public struct PasteboardEntry: Equatable {
    public let type: String
    public let data: Data
    public init(type: String, data: Data) { self.type = type; self.data = data }
}

/// What plain-text pasting needs from a pasteboard, so the logic can run against a fake.
public protocol PasteboardAccess: AnyObject {
    var changeCount: Int { get }
    /// The clipboard's plain-text form, if it has one.
    func plainText() -> String?
    /// Every item with every type it carries.
    func contents() -> [[PasteboardEntry]]
    /// Replaces the contents with this text alone. Returns the new change count.
    @discardableResult func replace(withText text: String) -> Int
    /// Replaces the contents with these items. Returns the new change count.
    @discardableResult func restore(_ items: [[PasteboardEntry]]) -> Int
}

/// Paste as plain text: put only the clipboard's text on it, paste, then put the original
/// back unless something else changed the clipboard in between. Nothing is kept once the
/// original is back, and nothing is logged.
public struct PlainPaste {
    public struct Pending: Equatable {
        public let original: [[PasteboardEntry]]
        /// The change count right after the plain text went on; any other value means
        /// someone else has written to the clipboard since.
        public let expectedChangeCount: Int
    }

    public private(set) var pending: Pending?
    public init() {}

    /// Called when the shortcut is pressed. Returns whether to send ⌘V. A second press
    /// before the original is back pastes the same plain text again rather than saving the
    /// plain text as the "original".
    public mutating func press(_ pasteboard: PasteboardAccess) -> Bool {
        if let pending {
            if pasteboard.changeCount == pending.expectedChangeCount { return true }
            self.pending = nil // something else wrote; its contents are the user's now
        }
        guard let text = pasteboard.plainText(), !text.isEmpty else { return false }
        let original = pasteboard.contents()
        guard !original.isEmpty else { return false } // nothing readable to put back
        let count = pasteboard.replace(withText: text)
        pending = Pending(original: original, expectedChangeCount: count)
        return true
    }

    /// Called a short delay after the paste. Returns whether the original was put back.
    @discardableResult
    public mutating func restore(_ pasteboard: PasteboardAccess) -> Bool {
        guard let pending else { return false }
        self.pending = nil
        guard pasteboard.changeCount == pending.expectedChangeCount else { return false }
        pasteboard.restore(pending.original)
        return true
    }
}

/// An `NSPasteboard`. The app passes the general pasteboard; tests pass a private one.
public final class SystemPasteboard: PasteboardAccess {
    private let pasteboard: NSPasteboard
    public init(_ pasteboard: NSPasteboard) { self.pasteboard = pasteboard }

    public var changeCount: Int { pasteboard.changeCount }

    public func plainText() -> String? { pasteboard.string(forType: .string) }

    public func contents() -> [[PasteboardEntry]] {
        (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { PasteboardEntry(type: type.rawValue, data: $0) } }
        }
    }

    public func replace(withText text: String) -> Int {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        // Clipboard-history apps skip this temporary copy (nspasteboard.org conventions).
        pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        return pasteboard.changeCount
    }

    public func restore(_ items: [[PasteboardEntry]]) -> Int {
        pasteboard.clearContents()
        let objects = items.map { entries -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for entry in entries { item.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type)) }
            return item
        }
        if !objects.isEmpty { pasteboard.writeObjects(objects) }
        return pasteboard.changeCount
    }
}
